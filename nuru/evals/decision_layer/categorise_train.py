def targets() -> list[tuple[str, dict[str, float]]]:
    """(request, {category: p(true)}) for every training request."""
    out = []
    for request, labels in TRAIN:
        names = set(labels.split())
        p = {c: YES if c in names else NO for c in CATEGORIES}
        p.update(SOFT.get(request, {}))
        p.update(SOFT_V3.get(request, {}))
        p.update(SOFT_V4.get(request, {}))
        out.append((request, p))
    return out


